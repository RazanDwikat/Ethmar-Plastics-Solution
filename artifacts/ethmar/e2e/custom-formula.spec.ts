import {test,expect} from './analyst-fixture';
import {readFile} from 'node:fs/promises';
import {upload,localData} from './helpers';
import {samples} from '../src/lib/samples';
test('analyst builder validates, previews, persists and imports; manager sees custom evidence',async({page})=>{
 await page.goto('/');await upload(page,'upload-file',samples[0].csv);
 await page.getByRole('button',{name:/Continue to row type/}).click();await page.getByTestId('button-confirm-shape').click();
 await page.locator('summary').filter({hasText:'Advanced settings'}).click();
 await page.getByRole('button',{name:'Add measurement',exact:true}).click();
 const card=page.locator('[data-testid^="measurement-card-"]').last();
 await card.locator(':scope > summary').click();
 await card.getByLabel('Display name',{exact:true}).fill('Waste formula');
 await card.getByLabel('Template').selectOption('Custom formula');
 const expression=card.locator('textarea');
 await expression.fill('([Scrap total]');
 await expect(card.locator('[data-testid^="formula-preview-"]')).toContainText('Missing closing');
 await expect(page.getByTestId('confirm-setup')).toBeDisabled();
 await expression.fill('');
 await card.locator('.formula-tools select').selectOption('Scrap total');
 await card.getByRole('button',{name:'Insert divide',exact:true}).click();
 await card.locator('.formula-tools select').selectOption('Material input total');
 await card.getByRole('button',{name:'Insert multiply',exact:true}).click();
 await card.getByRole('button',{name:'Insert number',exact:true}).click();
 await card.locator('[data-testid^="formula-unit-"]').selectOption('percent');
 await card.locator('[data-testid^="formula-decimals-"]').selectOption('1');
 await card.locator('[data-testid^="headline-"]').check();
 await card.locator('[data-testid^="required-"]').check();
 await expect(card.locator('[data-testid^="formula-preview-"]')).toContainText('5.0%');
 await page.screenshot({path:'../../generated-artifacts/formula-builder.jpg',fullPage:true});
 page.once('dialog',d=>d.accept('Formula setup'));await page.getByTestId('confirm-setup').click();
 await expect(page.getByTestId('setup-saved')).toBeVisible();
 page.once('dialog',d=>d.accept('Formula setup'));
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Save / Export setup'}).click();
 const profile=JSON.parse(await readFile(await (await download).path(),'utf8'));
 expect(profile.setup.measurements.at(-1).formula).toContain('Scrap total');
 await page.getByRole('button',{name:'Edit setup',exact:true}).click();
 const importer=page.getByTestId('import-setup-json');
 await page.locator('details').filter({has:importer}).evaluateAll(els=>els.forEach(e=>(e as HTMLDetailsElement).open=true));
 await importer.setInputFiles({name:'setup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(profile))});
 await expect(page.getByTestId('import-setup-success')).toBeVisible();
 await expect.poll(async()=> (await localData(page)).profiles.length).toBe(2);
 await page.reload();await page.getByRole('button',{name:'Sign out',exact:true}).click();await page.getByTestId('signin-manager').click();await upload(page,'manager-upload',samples[0].csv);
 await page.getByTestId('continue-comparison').click();
 const result=page.locator('.metric-card').filter({has:page.getByRole('heading',{name:'Waste formula',exact:true})});
 await expect(result).toContainText('5.0%');await expect(result).toContainText('10.0%');
 await result.getByRole('button').filter({hasText:'5.0%'}).click();
 await expect(page.getByRole('dialog')).toContainText('Material input total');
 await expect(page.getByRole('dialog')).toContainText('1,000');
 await expect(page.getByRole('dialog')).toContainText('Scrap total');
});
test('invalid imported formula cannot become a saved setup',async({page})=>{
 await page.goto('/');await upload(page,'upload-file',samples[0].csv);
 await page.getByRole('button',{name:/Continue to row type/}).click();await page.getByTestId('button-confirm-shape').click();
 const importer=page.getByTestId('import-setup-json');
 await page.locator('details').filter({has:importer}).evaluateAll(els=>els.forEach(e=>(e as HTMLDetailsElement).open=true));
 await importer.setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"setup":{"formula":"alert(1)"}}')});
 await expect(page.getByTestId('import-setup-error')).toContainText('No setup was imported');
 expect((await localData(page)).profiles).toEqual([]);
});
