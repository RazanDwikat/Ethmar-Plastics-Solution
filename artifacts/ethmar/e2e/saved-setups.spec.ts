import {readFile} from 'node:fs/promises';
import {test,expect} from './analyst-fixture';
import {upload,localData,saved} from './helpers';
import {samples} from '../src/lib/samples';

test('saved setup library preserves edits, transfers, manager preference and deletion',async({page})=>{
 await page.getByTestId('nav-saved-setups').click();
 await expect(page.getByRole('heading',{name:'No saved setups yet'})).toBeVisible();
 await page.getByRole('button',{name:'Setup · analyst'}).click();
 await upload(page,'upload-file',samples[0].csv);
 await page.getByTestId('continue-mapping').click();
 await page.getByTestId('button-confirm-shape').click();
 page.once('dialog',d=>d.accept('Library original'));
 await page.getByTestId('confirm-setup').click();
 await saved(page);
 const initial=await localData(page),original=initial.profiles[0];
 await page.getByTestId('done-saved-setups').click();
 const originalCard=page.getByTestId(`saved-setup-${original.id}`);
 await expect(originalCard).toContainText('production.csv');
 await originalCard.getByRole('button',{name:'View full setup'}).click();
 await expect(page.getByRole('dialog')).toContainText('Column mappings');
 await expect(page.getByRole('dialog')).toContainText('Scrap total ÷ Material input total × 100');
 await page.getByRole('button',{name:'Close Library original'}).click();
 await originalCard.getByRole('button',{name:'Duplicate'}).click();
 await expect.poll(async()=> (await localData(page)).profiles.length).toBe(2);
 const copy=(await localData(page)).profiles.find(p=>p.id!==original.id)!;
 const copyCard=page.getByTestId(`saved-setup-${copy.id}`);
 page.once('dialog',d=>d.accept('Library revised'));
 await copyCard.getByRole('button',{name:'Rename'}).click();
 await expect(copyCard).toContainText('Library revised');
 await copyCard.getByRole('button',{name:'Edit',exact:true}).click();
 await page.locator('summary').filter({hasText:'Advanced settings'}).click();
 const measurement=page.getByTestId(`measurement-card-${copy.setup.measurements[0].id}`);
 await measurement.locator('summary').click();
 await measurement.getByRole('textbox',{name:'Display name',exact:true}).fill('Waste fraction edited');
 await page.getByTestId('confirm-setup').click();
 await expect(copyCard).toBeVisible();
 expect((await localData(page)).profiles.find(p=>p.id===copy.id)?.setup.measurements[0].label).toBe('Waste fraction edited');
 expect((await localData(page)).workspace?.setup).toEqual(initial.workspace?.setup);
 const downloaded=page.waitForEvent('download');
 await copyCard.getByRole('button',{name:'Export JSON'}).click();
 const download=await downloaded,text=await readFile((await download.path())!,'utf8');
 expect(JSON.parse(text).sourceFileName).toBe('production.csv');
 await page.getByTestId('import-setup-json').setInputFiles({name:'saved.json',mimeType:'application/json',buffer:Buffer.from(text)});
 await expect(page.getByTestId('import-setup-success')).toBeVisible();
 const imported=(await localData(page)).profiles.find(p=>p.id!==original.id&&p.id!==copy.id)!;
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByTestId('signin-manager').click();
 await expect(page.getByRole('button',{name:'Rename',exact:true})).toHaveCount(0);
 await page.getByTestId(`choose-setup-${imported.id}`).click();
 await page.reload();
 await expect(page.getByTestId('manager-setup')).toHaveValue(imported.id);
 await page.getByRole('button',{name:'Sign out',exact:true}).click();
 await page.getByTestId('signin-analyst').click();
 await page.getByTestId('nav-saved-setups').click();
 page.once('dialog',async d=>{expect(d.message()).toContain('Managers will no longer be able to choose it');await d.accept()});
 await page.getByTestId(`saved-setup-${imported.id}`).getByRole('button',{name:'Delete',exact:true}).click();
 await expect(page.getByTestId(`saved-setup-${imported.id}`)).toHaveCount(0);
 await page.reload();
 expect((await localData(page)).profiles.some(p=>p.id===imported.id)).toBe(false);
});
